"""Explicit combo sets: ALF's substituent groups and their pairs.

A system's manifest lists combos generated by subset enumeration, which for
large sites holds only pairs. ALF ran those systems in groups of substituents
(``pretraining/<system>_group*``), and running the same groups makes the cost
comparison direct. Per system, ``combo_sets:`` defines named sets::

    systems:
      - name: luis_bace_solvent
        ...
        combo_sets:
          groups: alf_groups          # one combo per ALF group
          group_pairs: alf_group_pairs  # every within-site pair of those groups
          ref_pairs: alf_group_ref_pairs  # only each group's reference vs the others
          # or explicit groups, {site: [subs]} with the first sub the reference,
          # and pairs from them (a system without ALF runs):
          # mine: [{1: [3, 2], 2: [15, 6, 7]}]
          # mine_ref_pairs: {pairs_of: mine, reference_only: true}
    alf_root: /path/to/pretraining   # where <system>_group* live

A curriculum stage selects a set with ``combo_set: <name>``.

ALF groups are read from each group's first run's ``graph_info.json``, which
names the fragment behind every node; the dataset's own ``prep/`` copy of it is
matched (it may have been re-prepped), with a warning wherever ALF's runs used
a different file. Some groups were prepared with the
system's numbering and some with their own (site1_sub1..n), so each fragment
is matched to the system's by content (source ligand, atom names, types and
charges), not by name. A site with one substituent in a group is a fixed
substituent, not a perturbation; it is dropped (the combo keeps that site at
its first substituent, like any single-site combo). A system without
``_group*`` datasets uses its single ALF dataset as one group.
"""
import json
import re
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from mllf.file_handling.manifests import register_explicit_combos

ALF_GROUPS = 'alf_groups'
ALF_GROUP_PAIRS = 'alf_group_pairs'
# Only the pairs between each group site's reference (its first substituent)
# and the others: enough to place every b, at a fraction of the runs.
ALF_GROUP_REF_PAIRS = 'alf_group_ref_pairs'


def _natural_key(p: Path):
    m = re.search(r'(\d+)$', p.name)
    return (int(m.group(1)) if m else 10 ** 9, p.name)


def _rtf_signature(path) -> Tuple[Optional[str], tuple]:
    """(source-ligand tag, sorted (atom name, type, charge)) of a fragment's
    pres.rtf: the substituent's identity independent of its numbering, its
    PRES name and its coordinates (ALF groups were sometimes prepared with
    local numbering, site1_sub1..n, and their own coordinate frame)."""
    source, atoms = None, []
    with open(path, errors='replace') as f:
        for line in f:
            m = re.match(r'\*\s*\(fragment from (\d+)\)', line)
            if m:
                source = m.group(1)
            elif line.startswith('ATOM'):
                p = line.split()
                if len(p) >= 4:
                    try:
                        atoms.append((p[1], p[2], round(float(p[3]), 4)))
                    except ValueError:
                        pass
    return source, tuple(sorted(atoms))


def _alf_dataset_dirs(system: str, root: Path) -> List[Path]:
    """``<system>_group*`` under root (``_vac`` also as ``_vacuum``), else the
    ``<system>`` dataset itself as one group."""
    names = [system] + ([system[:-4] + '_vacuum'] if system.endswith('_vac') else [])
    for name in names:
        groups = sorted(root.glob(f"{name}_group*"), key=_natural_key)
        if groups:
            return groups
    return [root / name for name in names if any((root / name).glob('run[0-9]*/graph_info.json'))][:1]


def read_alf_groups(system: str, alf_root, input_dir) -> Tuple[List[Dict[int, List[int]]], List[str]]:
    """ALF's groups for ``system``: [{site: [subs in ALF's node order]}] in the
    system's own numbering, and warnings.

    Each group node's fragment is matched to the input_dir fragment with the
    same content (``_rtf_signature``); failing that, with the same atoms
    alone if that is unique. A node with no match is dropped (the system was
    prepared without that substituent), as is a site left with one
    substituent (fixed, not perturbed)."""
    root = Path(alf_root)
    prep = Path(input_dir) / 'prep'
    ours: Dict[tuple, List[Tuple[int, int]]] = {}
    by_atoms: Dict[tuple, List[Tuple[int, int]]] = {}
    for f in prep.glob('site*_sub*_pres.rtf'):
        m = re.match(r'site(\d+)_sub(\d+)_', f.name)
        if m:
            sig = _rtf_signature(f)
            ours.setdefault(sig, []).append((int(m.group(1)), int(m.group(2))))
            by_atoms.setdefault(sig[1], []).append((int(m.group(1)), int(m.group(2))))
    groups, warnings = [], []
    for gdir in _alf_dataset_dirs(system, root):
        info_path = next((r / 'graph_info.json' for r in sorted(gdir.glob('run[0-9]*'), key=_natural_key)
                          if (r / 'graph_info.json').exists()), None)
        if info_path is None:
            warnings.append(f"{gdir.name}: no run with graph_info.json; skipped")
            continue
        nodes = json.loads(info_path.read_text()).get('sites', {})
        group: Dict[int, List[int]] = {}
        for label, node in sorted(nodes.items(), key=lambda kv: (kv[1]['site'], kv[1]['sub'])):
            # The dataset's own prep copy (the master file the node names) is
            # what pretraining used and may carry corrections (e.g. re-prepped
            # fragments); the original file is what ALF's runs simulated.
            src = node.get('filepath')
            fname = (node.get('master') + '_pres.rtf') if node.get('master') else \
                Path(node.get('filename') or src or '').name
            copy = gdir / 'prep' / fname
            use = copy if copy.exists() else (Path(src) if src else None)
            if use is None or not use.exists():
                warnings.append(f"{gdir.name}: {label}: no fragment file ({copy}, {src}); dropped")
                continue
            sig = _rtf_signature(use)
            if use == copy and src and Path(src).exists() and _rtf_signature(src) != sig:
                warnings.append(f"{gdir.name}: {label}: ALF's runs used a different fragment "
                                f"({src}) than the dataset's prep copy; its ALF biases and cost "
                                f"are not for this substituent")
            hits = ours.get(sig) or (by_atoms.get(sig[1]) if len(by_atoms.get(sig[1], [])) == 1 else None)
            if not hits:
                warnings.append(f"{gdir.name}: {label} ({Path(src).name}) matches no substituent "
                                f"in {prep}; dropped")
                continue
            if len(hits) > 1:
                warnings.append(f"{gdir.name}: {label} matches {hits}; using {hits[0]}")
            site, sub = hits[0]
            if sub not in group.setdefault(site, []):
                group[site].append(sub)
        for site in [s for s, subs in group.items() if len(subs) < 2]:
            warnings.append(f"{gdir.name}: site {site} has one substituent "
                            f"(sub {group[site][0]}); treated as fixed")
            del group[site]
        if group:
            groups.append(group)
    return groups, warnings


def group_combo_info(prefix: str, index: int, group: Dict[int, List[int]], out_dir) -> Dict:
    """combo_info (create_single_combination_dir) for one group; each site's
    first substituent is its reference. The name keeps the
    ``site{n}_subs_{a}_{b}`` parts the curriculum filters read."""
    sites = sorted(group)
    subs = [s for site in sites for s in group[site]]
    counts = tuple(len(group[site]) for site in sites)
    name = f"{prefix}{index:02d}_" + '__'.join(
        f"site{site}_subs_{'_'.join(str(s) for s in group[site])}" for site in sites)
    return {'name': name, 'path': str(Path(out_dir) / name), 'sites': sites, 'subs': subs,
            'subs_per_site_counts': counts if len(sites) > 1 else None, 'counter': index}


def reversed_pair(combo_path) -> Optional[str]:
    """The reverse-orientation partner of a one-site pair combo
    (``pair07_site1_subs_1_9`` -> ``pair07r_site1_subs_9_1``, in the same
    directory): the same pair with lambda starting on the other substituent.
    Registered for on-demand creation; returns its path, or None if
    ``combo_path`` is not a one-site pair (or is itself a partner)."""
    p = Path(combo_path)
    m = re.match(r'pair(\d+)_site(\d+)_subs_(\d+)_(\d+)$', p.name)
    if not m:
        return None
    index, site, a, b = (int(x) for x in m.groups())
    info = group_combo_info('pair', index, {site: [b, a]}, p.parent)
    info['name'] = info['name'].replace(f'pair{index:02d}_', f'pair{index:02d}r_', 1)
    info['path'] = str(p.parent / info['name'])
    register_explicit_combos([info])
    return info['path']


def group_pairs(groups: List[Dict[int, List[int]]],
                reference_only: bool = False) -> List[Tuple[int, int, int]]:
    """Unique within-site pairs (site, a, b) over the groups, a before b in
    the group's order (so a group's reference comes first). reference_only:
    only pairs with the group site's reference."""
    seen, out = set(), []
    for group in groups:
        for site, subs in group.items():
            for i in range(1 if reference_only else len(subs)):
                for j in range(i + 1, len(subs)):
                    key = (site, min(subs[i], subs[j]), max(subs[i], subs[j]))
                    if key not in seen:
                        seen.add(key)
                        out.append((site, subs[i], subs[j]))
    return out


def build_combo_sets(sys_entry: Dict, alf_root=None) -> Tuple[Dict[str, List[str]], List[str]]:
    """The system's ``combo_sets`` as {set name: [combo paths]}, registered
    for on-demand creation, plus warnings."""
    spec = sys_entry.get('combo_sets') or {}
    if not spec:
        return {}, []
    system = sys_entry.get('name')
    out_dir = Path(sys_entry['out_dir'])
    warnings: List[str] = []
    alf: Optional[List[Dict[int, List[int]]]] = None
    sets: Dict[str, List[str]] = {}
    groups_of: Dict[str, List[Dict[int, List[int]]]] = {}   # explicit group sets, by name
    infos: List[Dict] = []
    for set_name, how in spec.items():
        pairs_mode = None          # None, 'all' or 'ref'
        if isinstance(how, dict):
            # {pairs_of: <explicit group set>, reference_only: bool}
            src = how.get('pairs_of')
            if src not in groups_of:
                raise ValueError(f"{system}: combo set {set_name}: pairs_of {src!r} must name "
                                 f"an explicit group set defined before it")
            groups = groups_of[src]
            pairs_mode = 'ref' if how.get('reference_only') else 'all'
        elif how in (ALF_GROUPS, ALF_GROUP_PAIRS, ALF_GROUP_REF_PAIRS):
            if alf is None:
                if not alf_root:
                    raise ValueError(f"{system}: combo_sets {how!r} needs alf_root in the config")
                alf, w = read_alf_groups(system, alf_root, sys_entry['input_dir'])
                warnings += w
                if not alf:
                    warnings.append(f"no ALF groups found for {system} under {alf_root}")
            groups = alf
        elif isinstance(how, list):
            groups = [{int(k): [int(s) for s in v] for k, v in g.items()} for g in how]
            groups_of[set_name] = groups
        else:
            raise ValueError(f"{system}: unknown combo set {set_name}: {how!r}")
        if how == ALF_GROUP_PAIRS:
            pairs_mode = 'all'
        elif how == ALF_GROUP_REF_PAIRS:
            pairs_mode = 'ref'
        if pairs_mode:
            set_infos = [group_combo_info('pair', n, {site: [a, b]}, out_dir)
                         for n, (site, a, b) in enumerate(
                             group_pairs(groups, reference_only=pairs_mode == 'ref'), start=1)]
        else:
            set_infos = [group_combo_info('group', n, g, out_dir)
                         for n, g in enumerate(groups, start=1)]
        infos += set_infos
        sets[set_name] = [i['path'] for i in set_infos]
    register_explicit_combos(infos)
    return sets, warnings
